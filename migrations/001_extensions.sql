-- ----------------------------------------------------------------------------
-- pg_trgm برای جست‌وجوی تقریبی نام محصول لازم است: نام قطعه را کاربر اغلب
-- ناقص یا با املای متفاوت می‌نویسد («فیلتر روغن» در برابر «فیلتر روغن موتور»).
--
-- توجه عملیاتی: ساختن افزونه روی PostgreSQL مدیریت‌شده به دسترسی نیاز دارد.
-- اگر ارائه‌دهنده اجازه ندهد، این مهاجرت با خطای روشن متوقف می‌شود — که
-- عمدی است: بهتر است همان لحظه بدانیم تا اینکه جست‌وجو بی‌سروصدا ضعیف شود.
-- در آن حالت جست‌وجو به ILIKE تنزل پیدا می‌کند و باید آگاهانه تصمیم گرفته شود.
-- ============================================================================

CREATE EXTENSION IF NOT EXISTS pg_trgm;
